import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { writeAtomic } from './lib/io.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const { source } = JSON.parse(await readFile(resolve(root, 'data/locales/cards.json'), 'utf8'));
const records = new Map();
for (const [language, column] of [['zh-CN', 1], ['en', 2], ['ja', 3]]) {
  const spec = source.files[language], path = resolve(root, spec.path);
  const hash = createHash('sha256').update(await readFile(path)).digest('hex');
  if (hash !== spec.sha256) throw new Error('Locale snapshot checksum mismatch: ' + language);
  const database = new DatabaseSync(path, { readOnly: true });
  try {
    for (const row of database.prepare('SELECT t.id, t.name, d.alias FROM texts t JOIN datas d ON t.id=d.id ORDER BY t.id').all()) {
      if (!records.has(row.id)) records.set(row.id, [row.id, '', '', '', Number(row.alias) || 0]);
      records.get(row.id)[column] = row.name;
    }
  } finally { database.close(); }
}
const rows = [...records.values()].sort((a, b) => a[0] - b[0]);
const safe = value => JSON.stringify(value).replace(/</g, '\\u003c');
await writeAtomic(resolve(root, 'src/card-catalog.js'),
  '/* Generated by scripts/build-card-catalog.mjs from ' + source.commit + '. Do not edit. */\n' +
  '(function(root){\nconst rows=[\n' + rows.map(safe).join(',\n') + '\n];\nroot.DuelCardCatalog=rows;\n' +
  "if(typeof module!=='undefined')module.exports=rows;\n})(globalThis);\n");
console.log('Offline card catalog: ' + rows.length + ' multilingual records.');
